// Sketch 034: data.js = what the Stack panel reads from each project's .planning/research/STACK.md:
// the decision (Labelore's "The Decision, Stated Once" / Cinedise's "Headline"), the recommended
// stack by section, and the alternatives considered (both table shapes).
// Run: node .planning/sketches/034-research-stack/gen-data.mjs <cinedise-research-dir>
import { readFileSync, writeFileSync } from 'node:fs';
const HERE = new URL('.', import.meta.url).pathname;
const SOURCES = { labelore: `${HERE}../../research`, cinedise: process.argv[2] };
if (!SOURCES.cinedise) { console.error('usage: gen-data.mjs <cinedise-research-dir>'); process.exit(1); }
function sections(src) {
  const out = []; let fence = false;
  src.split('\n').forEach((line) => {
    if (/^(```|~~~)/.test(line)) fence = !fence;
    const m = !fence && /^(#{1,4}) (.+)$/.exec(line);
    if (m) out.push({ depth: m[1].length, title: m[2].trim(), body: [] });
    else if (out.length) out[out.length - 1].body.push(line);
  });
  return out;
}
function table(lines) {
  const rows = lines.filter((l) => /^\|/.test(l.trim()) && !/^\|\s*:?-{3,}/.test(l.trim())).map((l) => l.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim()));
  return rows.length ? { head: rows[0], rows: rows.slice(1) } : null;
}
function paragraphs(lines) {
  const out = []; let cur = [];
  for (const l of lines) { if (!l.trim() || /^-{3,}$/.test(l.trim())) { if (cur.length) out.push(cur.join(' ')); cur = []; } else cur.push(l.trim()); }
  if (cur.length) out.push(cur.join(' '));
  return out;
}
function decision(secs) {
  const s = secs.find((x) => x.depth === 2 && /^(The Decision|Headline)/i.test(x.title));
  if (!s) return null;
  const ps = paragraphs(s.body);
  const reasons = ps.filter((p) => /^\d+\.\s/.test(p)).map((p) => { const t = p.replace(/^\d+\.\s+/, ''); const m = /^\*\*(.+?)\*\*\s*(.*)$/.exec(t); return m ? { lead: m[1], body: m[2] } : { lead: null, body: t }; });
  const prose = ps.filter((p) => !/^\d+\.\s/.test(p));
  const head = prose[0] || '';
  const bold = /^\*\*(.+?)\*\*\s*$/.exec(head);
  const verdict = bold ? bold[1] : head;
  const over = /^(.+?),?\s+over\s+(.+?)\.?$/.exec(verdict.replace(/\*\*/g, ''));
  return { verdict, chosen: over ? over[1] : null, rejected: over ? over[2].replace(/\.$/, '') : null, rest: prose.slice(1), reasons };
}
function stack(secs) {
  const i = secs.findIndex((x) => x.depth === 2 && /^Recommended Stack/i.test(x.title));
  const groups = [];
  for (let j = i + 1; j < secs.length && secs[j].depth > 2; j++) {
    const t = table(secs[j].body); if (!t) continue;
    const m = /^(.+?)\s*\((.+)\)\s*$/.exec(secs[j].title);
    groups.push({ title: m ? m[1] : secs[j].title, note: m ? m[2] : null, whyLabel: t.head[3] || 'Why', items: t.rows.map((r) => ({ name: r[0].replace(/\*\*/g, ''), version: r[1] || null, purpose: r[2] || null, why: r[3] || null })) });
  }
  return groups;
}
function alternatives(secs) {
  const s = secs.find((x) => x.depth === 2 && /^Alternatives Considered/i.test(x.title));
  const t = s && table(s.body); if (!t) return null;
  const h = t.head.map((x) => x.toLowerCase());
  const ci = h.findIndex((x) => /category/.test(x)), ri = h.findIndex((x) => /recommended/.test(x)), ai = h.findIndex((x) => /^alternative/.test(x));
  const ti = h.findIndex((x, k) => k !== ci && k !== ri && k !== ai);
  const kind = /why not/i.test(t.head[ti]) ? 'whynot' : 'when';
  return { kind, rows: t.rows.map((r) => ({ category: ci >= 0 ? r[ci] : null, chosen: r[ri], alt: r[ai], text: r[ti] })) };
}
const out = {};
for (const [key, dir] of Object.entries(SOURCES)) {
  const secs = sections(readFileSync(`${dir}/STACK.md`, 'utf8'));
  out[key] = { decision: decision(secs), stack: stack(secs), alternatives: alternatives(secs) };
}
writeFileSync(`${HERE}data.js`, `// Generated by gen-data.mjs from two projects' .planning/research/STACK.md\nwindow.STK = ${JSON.stringify(out, null, 1)};\n`);
console.log('wrote data.js');
