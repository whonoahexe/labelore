// Sketch 029 data: 028's ten real notes (written by ../027-todo-page/gen-data.mjs) plus two of
// labelore's own — the sketches-page quick note and the artifact survey explore note — so every note
// shape is here: dense labelled, unlabelled prose, one-liners, a question, and three explore notes.
// Run: node .planning/sketches/029-note-gist/gen-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
const HERE = new URL('.', import.meta.url).pathname;
const REPO = new URL('../../../', import.meta.url).pathname;
const ctx = { window: {} };
vm.runInNewContext(readFileSync(`${HERE}../028-note-page/data.js`, 'utf8'), ctx);
const DATA = ctx.window.DATA;

function read(path) {
  const raw = readFileSync(REPO + path, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  const fm = {};
  for (const line of (m?.[1] ?? '').split('\n')) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) fm[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1');
  }
  return { raw, fm, body: raw.slice(m ? m[0].length : 0).trim() };
}

const add = (key, label, path) => {
  const { raw, fm, body } = read(path);
  const doc = 'title' in fm;
  DATA[key] = {
    key, label, project: 'labelore', path, date: fm.date ?? null,
    promoted: doc ? null : fm.promoted === 'true', title: fm.title ?? null, context: fm.context ?? null,
    kind: doc ? 'document' : 'quick', body, todos: [], raw,
  };
};
add('lsketch', 'labelore · quick · Want / Open question ×2 / Today, promoted, untraced', '.planning/notes/2026-10-23-sketches-page-in-labelore.md');
add('lsurvey', 'labelore · explore note · 89 lines, survey figures', '.planning/notes/artifact-structure-survey.md');

writeFileSync(`${HERE}data.js`, `// generated by ./gen-data.mjs — real note files, read only\nwindow.DATA = ${JSON.stringify(DATA, null, 1)};\n`);
console.log(Object.keys(DATA).join(' '));
