// Sketch 030: data.js = the four retrospective sections per milestone, lifted verbatim from
// .planning/RETROSPECTIVE.md. Run: node .planning/sketches/030-milestone-retro-dialog/gen-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const HERE = new URL('.', import.meta.url).pathname;
const src = readFileSync(`${HERE}../../RETROSPECTIVE.md`, 'utf8');
const WANT = { 'What Worked': 'worked', 'What Was Inefficient': 'inefficient', 'Patterns Established': 'patterns', 'Key Lessons': 'lessons' };
const out = {};
const lineOf = (v) => src.split('\n').findIndex((l) => l.startsWith(`## Milestone: ${v} `));
for (const block of src.split(/^## Milestone: /m).slice(1)) {
  const version = block.match(/^(v[\d.]+)/)[1];
  const sections = {};
  for (const sec of block.split(/^### /m).slice(1)) {
    const [head, ...lines] = sec.split('\n');
    const key = WANT[head.trim()];
    if (!key) continue;
    const items = [];
    for (const line of lines) {
      if (/^(- |\d+\. )/.test(line)) items.push(line.replace(/^(- |\d+\. )/, ''));
      else if (/^\s+\S/.test(line) && items.length) items[items.length - 1] += ' ' + line.trim();
    }
    const at = src.split('\n').findIndex((l, i) => l === `### ${head.trim()}` && i > lineOf(version)) + 1;
    sections[key] = { at, items: items.map((text) => {
      const m = text.match(/^\*\*(.+?)\*\*\s*(.*)$/);
      return m ? { lead: m[1], body: m[2] } : { lead: null, body: text };
    }) };
  }
  out[version] = { line: (block.match(/^.*$/m)[0]), at: lineOf(version) + 1, sections };
}
writeFileSync(`${HERE}data.js`, `// Generated by gen-data.mjs from .planning/RETROSPECTIVE.md\nwindow.RETRO = ${JSON.stringify(out, null, 1)};\n`);
