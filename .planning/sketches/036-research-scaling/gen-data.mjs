// Sketch 036: scale-data.js = the "Scaling Considerations" section of each project's
// .planning/research/ARCHITECTURE.md (Scalability spelling too): the lead sentence, the table read as
// scale tiers × concerns, and the numbered Scaling Priorities split into the problem and its fix.
// arch-data.js is 032's data.js, unchanged (structure, anti-patterns, build order).
// Run: node .planning/sketches/036-research-scaling/gen-data.mjs <cinedise-research-dir> <protocol-research-dir>
import { readFileSync, writeFileSync } from 'node:fs';
const HERE = new URL('.', import.meta.url).pathname;
const SOURCES = { labelore: `${HERE}../../research`, cinedise: process.argv[2], protocol: process.argv[3] };
if (!SOURCES.cinedise || !SOURCES.protocol) { console.error('usage: gen-data.mjs <cinedise-research-dir> <protocol-research-dir>'); process.exit(1); }

function sections(src) {
  const out = []; let fence = false;
  src.split('\n').forEach((line) => {
    if (/^(```|~~~)/.test(line)) fence = !fence;
    const m = !fence && /^(#{1,4}) (.+)$/.exec(line);
    if (m) out.push({ depth: m[1].length, title: m[2].trim(), body: [] });
    else if (out.length) out[out.length - 1].body.push(line);
  });
  return out;
}
const strip = (s) => s.replace(/^\d+\.\s*/, '');
const cells = (l) => l.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
// "Per shoot (hundreds of GB)" → name + the parenthetical as a quiet second line.
const tierName = (s) => { const m = /^(.*?)\s*\(([^)]+)\)\s*$/.exec(s); return m ? { name: m[1], detail: m[2] } : { name: s, detail: null }; };
// A cell that says nothing changes reads quiet; n/a reads as "doesn't apply".
const tone = (s) => /^n\/a$/i.test(s) ? 'na' : /^(unchanged|same|low|adequate)\.?$|no adjustments? needed/i.test(s) ? 'holds' : 'changes';

function scaling(src) {
  const secs = sections(src);
  const i = secs.findIndex((x) => x.depth === 2 && /^Scal(ing|ability) Considerations/i.test(strip(x.title)));
  if (i < 0) return null;
  const top = secs[i];
  const kids = []; for (let j = i + 1; j < secs.length && secs[j].depth > top.depth; j++) kids.push(secs[j]);
  const body = top.body;
  const t0 = body.findIndex((l) => /^\|/.test(l.trim()));
  const lead = body.slice(0, t0 < 0 ? body.length : t0).join('\n').trim().split(/\n\s*\n/)[0] || null;
  const rows = body.filter((l) => /^\|/.test(l.trim()) && !/^\|\s*:?-{3,}/.test(l.trim())).map(cells);
  const [head, ...data] = rows;
  let tiers, concerns;
  if (head.length === 2) {
    // Scale | Adjustments: each row is a tier, the one concern is the second header.
    tiers = data.map((r) => tierName(r[0]));
    concerns = [{ name: head[1], cells: data.map((r) => ({ text: r[1], tone: tone(r[1]) })) }];
  } else {
    tiers = head.slice(1).map(tierName);
    concerns = data.map((r) => ({ name: r[0].replace(/`/g, ''), code: /`/.test(r[0]), cells: r.slice(1).map((c) => ({ text: c, tone: tone(c) })) }));
  }
  const pri = kids.find((k) => /Scaling Priorities/i.test(k.title));
  const priorities = pri ? pri.body.join('\n').split(/\n(?=\d+\.\s)/).map((x) => x.trim()).filter((x) => /^\d+\.\s/.test(x)).map((x) => {
    const m = /^\d+\.\s*\*\*(.+?):?\*\*:?\s*([\s\S]+)$/.exec(x.replace(/\s*\n\s*/g, ' '));
    const label = m ? m[1].replace(/:$/, '') : null; let text = m ? m[2] : x.replace(/^\d+\.\s*/, '');
    // The fix: "— mitigated by …", ". Mitigation is …", ". Mitigated by …".
    let fix = null;
    const f = /\s*(?:—|–|-)\s*(mitigated\b[\s\S]*)$|\.\s+(Mitigat(?:ed|ion)\b[\s\S]*)$/i.exec(text);
    if (f) { fix = (f[1] || f[2]).trim(); text = text.slice(0, f.index).trim(); }
    if (fix) fix = fix.replace(/\s*-{3,}\s*$/, '');
    if (fix) fix = fix.charAt(0).toUpperCase() + fix.slice(1);
    return { label, text: text.replace(/\.$/, ''), fix, not: /^not\b/i.test(label || '') };
  }) : [];
  // Where each bottleneck bites: the cell that shares the most word stems with it (≥2), or nowhere.
  const stems = (s) => new Set((s.toLowerCase().match(/[a-z]{4,}/g) || []).map((w) => w.slice(0, 5)).filter((w) => !/^(with|this|that|only|from|once|than|when|which|relev|reall|first|secon|bottl|mitig)/.test(w)));
  priorities.forEach((p) => {
    if (p.not) return;
    const want = stems(p.text); let best = null;
    concerns.forEach((c, ci) => c.cells.forEach((cell, ti) => {
      const have = stems(`${c.name} ${cell.text}`); let n = 0; want.forEach((w) => have.has(w) && n++);
      if (n >= 2 && (!best || n > best.n)) best = { n, concern: ci, tier: ti };
    }));
    p.at = best ? { concern: best.concern, tier: best.tier } : null;
  });
  return { axis: head[0], shape: head.length === 2 ? 'tiers' : 'matrix', lead, tiers, concerns, priorities };
}

const out = {};
for (const [k, dir] of Object.entries(SOURCES)) out[k] = scaling(readFileSync(`${dir}/ARCHITECTURE.md`, 'utf8'));
writeFileSync(`${HERE}scale-data.js`, `// Generated by gen-data.mjs from three projects' .planning/research/ARCHITECTURE.md\nwindow.SCALE = ${JSON.stringify(out, null, 1)};\n`);
for (const [k, v] of Object.entries(out)) console.log(k, v.shape, v.tiers.length, 'tiers', v.concerns.length, 'concerns', v.priorities.map((p) => `${p.label} @${JSON.stringify(p.at)} fix:${!!p.fix}`).join(' | '));
