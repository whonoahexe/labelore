// Sketch 037: traps-data.js = the Performance Traps, Security Mistakes and UX Pitfalls tables of each
// project's .planning/research/PITFALLS.md: the lead paragraph, the header and the rows, with each
// column's role read from its header (name, what you notice / what could happen, the fix, when).
// pit-data.js is 035's data.js, unchanged (critical pitfalls, the check ledger).
// Run: node .planning/sketches/037-research-pitfall-tables/gen-data.mjs <cinedise-research-dir>
import { readFileSync, writeFileSync } from 'node:fs';
const HERE = new URL('.', import.meta.url).pathname;
const SOURCES = { labelore: `${HERE}../../research`, cinedise: process.argv[2] };
if (!SOURCES.cinedise) { console.error('usage: gen-data.mjs <cinedise-research-dir>'); process.exit(1); }

function sections(src) {
  const out = []; let fence = false;
  src.split('\n').forEach((line) => {
    if (/^(```|~~~)/.test(line)) fence = !fence;
    const m = !fence && /^(#{1,4}) (.+)$/.exec(line);
    if (m) out.push({ depth: m[1].length, title: m[2].trim(), body: [] });
    else if (out.length) out[out.length - 1].body.push(line);
  });
  return out;
}
const cells = (l) => l.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
const KINDS = [
  { key: 'performance', label: 'Performance', re: /^Performance Traps/i },
  { key: 'security', label: 'Security', re: /^Security Mistakes/i },
  { key: 'ux', label: 'UX', re: /^UX Pitfalls/i },
];
// A column's role from its header: the consequence (symptoms / risk / user impact), the fix
// (prevention / better approach), and when it breaks.
const role = (h) => /symptom|risk|impact/i.test(h) ? 'effect' : /prevent|better|instead|fix/i.test(h) ? 'fix' : /when/i.test(h) ? 'when' : 'other';

function tables(src) {
  const secs = sections(src);
  return KINDS.map((k) => {
    const s = secs.find((x) => x.depth === 2 && k.re.test(x.title.replace(/^\d+\.\s*/, '')));
    if (!s) return null;
    const t0 = s.body.findIndex((l) => /^\|/.test(l.trim()));
    const lead = s.body.slice(0, t0 < 0 ? s.body.length : t0).join('\n').trim().split(/\n\s*\n/)[0] || null;
    const rows = s.body.filter((l) => /^\|/.test(l.trim()) && !/^\|\s*:?-{3,}/.test(l.trim())).map(cells);
    const [head, ...data] = rows;
    if (!head) return null;
    const roles = head.map((h, i) => (i === 0 ? 'name' : role(h)));
    const items = data.map((r) => {
      const o = { name: r[0], fields: [] };
      head.forEach((h, i) => {
        if (i === 0) return;
        const f = { label: h, role: roles[i], text: r[i] || '' };
        if (roles[i] !== 'other' && !(roles[i] in o)) o[roles[i]] = f.text;
        o.fields.push(f);
      });
      return o;
    });
    return { key: k.key, label: k.label, title: s.title, lead, head, items };
  }).filter(Boolean);
}

const out = {};
for (const [k, dir] of Object.entries(SOURCES)) out[k] = tables(readFileSync(`${dir}/PITFALLS.md`, 'utf8'));
writeFileSync(`${HERE}traps-data.js`, `// Generated by gen-data.mjs from two projects' .planning/research/PITFALLS.md\nwindow.TRAPS = ${JSON.stringify(out, null, 1)};\n`);
for (const [k, v] of Object.entries(out)) console.log(k, v.map((t) => `${t.label}:${t.items.length} [${t.head.join(' | ')}] lead:${!!t.lead}`).join('  '));
