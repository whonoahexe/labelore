// Sketch 033: data.js = what the Features panel reads from each project's
// .planning/research/FEATURES.md: the feature landscape (table stakes, differentiators,
// anti-features, keeping Cinedise's #### groups) and the competitor feature analysis.
// Run: node .planning/sketches/033-research-features/gen-data.mjs <cinedise-research-dir>
import { readFileSync, writeFileSync } from 'node:fs';
const HERE = new URL('.', import.meta.url).pathname;
const SOURCES = { labelore: `${HERE}../../research`, cinedise: process.argv[2] };
if (!SOURCES.cinedise) { console.error('usage: gen-data.mjs <cinedise-research-dir>'); process.exit(1); }

function sections(src) {
  const out = []; let fence = false;
  src.split('\n').forEach((line) => {
    if (/^(```|~~~)/.test(line)) fence = !fence;
    const m = !fence && /^(#{1,4}) (.+)$/.exec(line);
    if (m) out.push({ depth: m[1].length, title: m[2].trim(), body: [] });
    else if (out.length) out[out.length - 1].body.push(line);
  });
  return out;
}
function table(lines) {
  const rows = lines.filter((l) => /^\|/.test(l.trim()) && !/^\|\s*:?-{3,}/.test(l.trim())).map((l) => l.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim()));
  return rows.length ? { head: rows[0], rows: rows.slice(1) } : null;
}
const prose = (lines) => lines.filter((l) => l.trim() && !/^\|/.test(l.trim()) && !/^-{3,}$/.test(l.trim())).join(' ').replace(/\s+/g, ' ').trim() || null;
const LEVEL = /\b(LOW-MEDIUM|MEDIUM-HIGH|MEDIUM-LOW|LOW|MEDIUM|HIGH)\b/;

// The biggest section matching re (with its deeper subsections), as rows tagged with their group.
function kind(secs, re) {
  let best = { items: [], lead: null };
  secs.forEach((x, i) => {
    if (x.depth < 2 || !re.test(x.title)) return;
    const items = []; const add = (t, group) => t && t.rows.forEach((r) => items.push({ group, cells: r, head: t.head }));
    add(table(x.body), null);
    for (let j = i + 1; j < secs.length && secs[j].depth > x.depth; j++) add(table(secs[j].body), secs[j].title.replace(/\s*\(.*\)\s*$/, ''));
    if (items.length > best.items.length) best = { items, lead: prose(x.body.filter((l) => !/^\|/.test(l.trim()))) };
  });
  return best;
}
const clean = (s) => (s || '').replace(/<br\s*\/?>/g, ' ').trim();
function landscape(secs) {
  const ts = kind(secs, /Table Stakes/i), df = kind(secs, /Differentiators/i), an = kind(secs, /Anti-Features/i);
  const feat = (it) => { const c = it.cells; const lv = (LEVEL.exec(c[2] || '') || [])[1] || null; return { name: clean(c[0]), group: it.group, why: clean(c[1]), complexity: lv, notes: clean(c[3]) || null }; };
  return {
    expected: { lead: ts.lead, items: ts.items.map(feat) },
    differentiators: { lead: df.lead, items: df.items.map(feat) },
    anti: { lead: an.lead, items: an.items.map((it) => ({ name: clean(it.cells[0]), group: it.group, requested: clean(it.cells[1]), problem: clean(it.cells[2]), instead: clean(it.cells[3]) })) },
  };
}
function competitors(secs) {
  const s = secs.find((x) => /Competitor Feature Analysis/i.test(x.title));
  const t = s && table(s.body);
  if (!t) return null;
  const rivals = t.head.slice(1, -1);
  return {
    rivals, ours: t.head[t.head.length - 1],
    rows: t.rows.map((r) => ({ feature: clean(r[0]), them: r.slice(1, -1).map(clean), ours: clean(r[r.length - 1]) })),
    note: prose(s.body.slice(s.body.findIndex((l, i) => i > 0 && !/^\|/.test(l.trim()) && s.body.slice(0, i).some((x) => /^\|/.test(x.trim()))))),
  };
}
const out = {};
for (const [key, dir] of Object.entries(SOURCES)) {
  const secs = sections(readFileSync(`${dir}/FEATURES.md`, 'utf8'));
  out[key] = { landscape: landscape(secs), competitors: competitors(secs) };
}
writeFileSync(`${HERE}data.js`, `// Generated by gen-data.mjs from two projects' .planning/research/FEATURES.md\nwindow.FEAT = ${JSON.stringify(out, null, 1)};\n`);
console.log('wrote data.js');
